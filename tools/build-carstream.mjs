import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, writeFile, access } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
export const CARSTREAM_CSP = "default-src 'none'; script-src 'self'; style-src 'self'; connect-src 'self'; media-src 'self'; img-src 'self'; font-src 'self'; base-uri 'none'; object-src 'none'; form-action 'self'";
const hash = value => createHash('sha256').update(value).digest('hex');
function replaceOnce(text, pattern, replacement, label) {
  const matches=[...text.matchAll(pattern)];if(matches.length!==1)throw new Error(`Expected exactly one ${label} in the canonical HTML.`);
  return text.replace(pattern,replacement);
}
/** Build only committed source bytes. Dirty working files cannot alter a pinned snapshot. */
export async function buildCarStream({ repo, revision, output }) {
  if (!/^[a-f0-9]{40}$/.test(revision || '')) throw new Error('A full canonical commit SHA is required.');
  const git = args => execFileSync('git',['-C',repo,...args],{maxBuffer:8*1024*1024});
  if(git(['rev-parse',revision+'^{commit}']).toString().trim()!==revision)throw new Error('Revision is not a commit.');
  try { await access(output); throw new Error('Output must not already exist; build into a fresh directory.'); }
  catch(error) { if(error.code!=='ENOENT')throw error; }
  const listing=git(['ls-tree','-rz',revision,'public/']).toString().split('\0').filter(Boolean),source=new Map();
  for(const row of listing){
    const match=/^(100644|100755) blob ([a-f0-9]{40})\tpublic\/([^\0]+)$/.exec(row);
    if(!match||match[3].includes('..')||match[3].startsWith('/')||match[3].includes('\\'))throw new Error('Unexpected canonical asset entry.');
    source.set(match[3],git(['cat-file','blob',match[2]]));
  }
  for(const name of ['index.html','app.js','runtime.js','runtime-core.js','discover.js','parental-controls.js'])if(!source.has(name))throw new Error('The pinned web revision lacks the local runtime contract: '+name);
  if(!source.get('runtime.js').toString().includes('installRuntimeServices'))throw new Error('The pinned runtime cannot accept phone services.');
  const originalHtml=source.get('index.html').toString();
  let html=replaceOnce(originalHtml,/<meta name="api-origin" content="[^"]*">/g,'<meta name="player-runtime" content="carstream"><meta name="api-prefix" content="/tw">','API origin');
  html=replaceOnce(html,/<meta http-equiv="Content-Security-Policy" content="[^"]*">/g,`<meta http-equiv="Content-Security-Policy" content="${CARSTREAM_CSP}">`,'CSP');
  html=replaceOnce(html,/<script type="module" src="\.\/app\.js"><\/script>/g,'<script type="module" src="./carstream-entry.js"></script>','entry module');
  html=html.replace(/<link rel="manifest"[^>]*>/g,'');
  source.set('index.html',Buffer.from(html));
  source.set('carstream-entry.js',Buffer.from(`// Generated by the canonical player build; do not edit in CarStream.\nimport { installRuntimeServices } from './runtime.js';\ntry {\n  const { connectRuntime } = await import('/carstream/host.js');\n  installRuntimeServices(await connectRuntime());\n  await import('./app.js');\n} catch(error) {\n  const target=document.querySelector('#loading p');\n  if(target)target.textContent=error?.message||'Open CarStream on the phone and scan Open Player again.';\n}\n`));
  const manifest={schema:1,repository:'to-shreds/torbox-web-player',revision,runtime:'carstream',apiPrefix:'/tw',csp:CARSTREAM_CSP,requiredHostModules:['/carstream/host.js'],requiresPhoneServices:true,assets:{}};
  await mkdir(output,{recursive:true});
  for(const [name,bytes] of [...source].sort(([a],[b])=>a < b ? -1 : a > b ? 1 : 0)){
    const path=join(output,name);await mkdir(resolve(path,'..'),{recursive:true});await writeFile(path,bytes);
    manifest.assets[name]={sha256:hash(bytes),bytes:bytes.length,generated:name==='index.html'||name==='carstream-entry.js'};
  }
  await writeFile(join(output,'TORBOX_WEB_REVISION'),revision+'\n');
  await writeFile(join(output,'asset-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  return manifest;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const args=process.argv.slice(2);if(args.length!==3)throw new Error('Usage: node tools/build-carstream.mjs <canonical-repo> <full-commit> <fresh-output>');
  const result=await buildCarStream({repo:resolve(args[0]),revision:args[1],output:resolve(args[2])});
  console.log(JSON.stringify({revision:result.revision,assets:Object.keys(result.assets).length,requiresPhoneServices:true}));
}
